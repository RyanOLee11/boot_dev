import pandas as pd
import re
import datetime

def _fmt_date(val):
    """Return SQL date expression or NULL for a pandas / python date-like value."""
    if pd.isna(val):
        return 'NULL'
    if not isinstance(val, (pd.Timestamp, datetime.date, datetime.datetime)):
        val = pd.to_datetime(val, errors='coerce')
    if pd.isna(val):
        return 'NULL'
    return f"TO_DATE('{val.strftime('%Y-%m-%d')}', 'YYYY-MM-DD')"

