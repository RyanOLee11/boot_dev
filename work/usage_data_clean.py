def clean_summit_data():
    # Load the Excel file into a DataFrame, only the 2025 sheet, without headers
    df = pd.read_excel('SUMMIT USAGE.xlsx', sheet_name='2025', header=None)

    # Define months and their corresponding row indices for usage and dollar amounts
    months = ['MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC']
    usage_rows = {month: idx for idx, month in enumerate(months, start=6)}   # Block 1: rows 6-13 (usage)
    dollar_rows = {month: idx for idx, month in enumerate(months, start=24)}  # Block 2: rows 24-31 (dollar)

    # Define corresponding first-of-month dates for 2025
    date_map_2025 = {month: pd.Timestamp(f'2025-{i+5}-01') for i, month in enumerate(months)}

    # Initialize lists to store transformed data
    transformed_data = []

    # Get meter numbers from the first row, starting from the second column (index 1)
    meter_numbers = df.iloc[0, 1:].dropna().tolist()

    # Normalize first column for matching
    df.iloc[:, 0] = df.iloc[:, 0].astype(str).str.strip().str.upper()

    # Debug: Print unique values in the first column
    print("Unique row labels in first column:", df.iloc[:, 0].unique())

    # Debug: Print sample rows around usage and dollar indices
    print("\nSample rows (5-15):")
    print(df.iloc[5:16, :5])  # First 5 columns for brevity
    print("\nSample rows (23-33):")
    print(df.iloc[23:34, :5])

    # Function to attempt converting a value to float, handling text
    def safe_float(value, is_dollar=False):
        if pd.isna(value):
            return None
        try:
            # If value is a string
            if isinstance(value, str):
                # For usage, only accept purely numeric strings (e.g., '6', '-72.27')
                if not is_dollar:
                    if not re.match(r'^-?\d*\.?\d+$', value.strip()):
                        return None
                # For dollar amounts, extract numeric portion (e.g., 'NEW ACCT NUMBER 2855.01' -> 2855.01)
                match = re.search(r'-?\d+\.?\d*', value)
                if match:
                    return float(match.group())
                return None
            return float(value)
        except (ValueError, TypeError):
            return None

    # Process 2025 data
    for meter in meter_numbers:
        print(f"\nProcessing meter: {meter}")
        meter_col_idx = df.iloc[0][df.iloc[0] == meter].index[0]  # Find column index for this meter
        for month in months:
            # Get usage from block 1 (rows 6-13)
            usage_row = usage_rows[month]  # e.g., MAY at row 6
            usage = df.loc[usage_row, meter_col_idx] if usage_row in df.index else None
            
            # Get dollar amount from block 2 (rows 24-31)
            dollar_row = dollar_rows[month]  # e.g., MAY at row 24
            dollar = df.loc[dollar_row, meter_col_idx] if dollar_row in df.index else None

            # Only add row if usage is a valid number
            usage_value = safe_float(usage, is_dollar=False)
            if usage_value is not None:
                dollar_value = safe_float(dollar, is_dollar=True)
                row_data = {
                    'ACCOUNT_NUMBER': str(meter),
                    'DATE': date_map_2025[month],
                    'USAGE_AMOUNT': usage_value,
                    'DOLLAR_AMOUNT': dollar_value
                }
                transformed_data.append(row_data)
                print(f"Added data for {month}, meter {meter}: usage={usage} (row {usage_row}), dollar={dollar} (row {dollar_row})")

    # Create DataFrame from transformed data
    result_df = pd.DataFrame(transformed_data)

    # get accounts data
    accounts_df = pd.read_excel('summit_accounts.xlsx')

    # Convert account numbers to strings before merging
    # alse remove any thing to the right of '/' in account numbers if it exists
    result_df["ACCOUNT_NUMBER"] = (
        result_df["ACCOUNT_NUMBER"]
        .astype(str)
        .str.strip()
        .str.replace(r'/.*', '', regex=True)   # remove "/" and everything after
    )
    accounts_df["METER_NUMBER"] = accounts_df["METER_NUMBER"].astype(str).str.strip()

    print(result_df.head())
    print(accounts_df.head())

    # merge with accounts_df to get location information
    result_df = result_df.merge(accounts_df[['LOCATION', 'METER_NUMBER']], left_on='ACCOUNT_NUMBER', right_on='METER_NUMBER', how='left')

#     create table rfi.intelex_summit_usage_tbl (
#     summit_usage_id                             number generated by default on null as identity 
#                                    constraint rfi_intelex_summit_id_pk primary key,
#     location                       varchar2(255 char),
#     meter_number                   varchar2(255 char),
#     read_date                      date,
#     usage_amount                   number,
#     dollar_amount                  number,
#     created                        date not null,
#     created_by                     varchar2(255 char) not null,
#     updated                        date not null,
#     updated_by                     varchar2(255 char) not null
# )
    with open('summit_insert_statements.sql', 'w') as f:
        for index, row in result_df.iterrows():
            insert_statement = f"""INSERT INTO rfi.intelex_summit_usage_tbl (
                location, meter_number, read_date, usage_amount, dollar_amount, created, created_by, updated, updated_by
            ) VALUES (
                '{row['LOCATION']}', '{row['ACCOUNT_NUMBER']}', TO_DATE('{row['DATE']}', 'YYYY-MM-DD'),
                {row['USAGE_AMOUNT']}, {row['DOLLAR_AMOUNT'] if pd.notna(row['DOLLAR_AMOUNT']) else 'NULL'},
                SYSDATE, 'SCRIPT', SYSDATE, 'SCRIPT'
            );\n"""
            f.write(insert_statement)
    # Save to a new Excel file
    result_df.to_excel('cleaned_summit_data.xlsx', index=False)

    print("Finished SUMMIT")

